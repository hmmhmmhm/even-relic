export const PHONE_STRINGS = { en, ko } as const;
export type PhoneStringKey = keyof typeof en;

export function resolvePhoneLocale(
  setting: PhoneLocaleSetting,
  browserLanguage: string,
): PhoneLocale {
  if (setting !== "system") return setting;
  return browserLanguage.toLowerCase().startsWith("ko") ? "ko" : "en";
}

export function translatePhone(
  locale: PhoneLocale,
  key: PhoneStringKey,
): string {
  return PHONE_STRINGS[locale][key];
}
